// Deterministic, dependency-free generator for the repository's OpenAPI 3.1
// JSON Schema subset. Unknown schema shapes stay unknown, never implicit any.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const source=new URL('../../internal/server/apispec/swagger.json',import.meta.url);
const output=new URL('../src/generated.ts',import.meta.url);
const bytes=await readFile(source);
const spec=JSON.parse(bytes);
const quote=JSON.stringify;
function schema(s={}) {
  if(s===true) return 'unknown';
  if(s===false) return 'never';
  if(s.$ref) {
    const name=s.$ref.replace('#/components/schemas/','');
    if(!spec.components.schemas[name]) throw Error(`Unresolved schema ${s.$ref}`);
    return `Schemas[${quote(name)}]`;
  }
  if(s.enum) return s.enum.map(quote).join(' | ')||'never';
  if(s.const!==undefined) return quote(s.const);
  if(s.oneOf||s.anyOf) return (s.oneOf||s.anyOf).map(x=>`(${schema(x)})`).join(' | ');
  if(s.allOf) return s.allOf.map(x=>`(${schema(x)})`).join(' & ');
  if(Array.isArray(s.type)) return s.type.map(type=>schema({...s,type})).join(' | ');
  let result;
  switch(s.type) {
    case 'string':result='string';break;
    case 'number':case 'integer':result='number';break;
    case 'boolean':result='boolean';break;
    case 'null':result='null';break;
    case 'array':result=`Array<${schema(s.items)}>`;break;
    case 'object':
      if(s.properties) {
        const fields=Object.keys(s.properties).sort().map(k=>`${quote(k)}${s.required?.includes(k)?'':'?'}: ${schema(s.properties[k])};`);
        if(s.additionalProperties) fields.push(`[key: string]: ${s.additionalProperties===true?'unknown':schema(s.additionalProperties)};`);
        result=`{ ${fields.join(' ')} }`;
      } else result=`Record<string, ${s.additionalProperties&&s.additionalProperties!==true?schema(s.additionalProperties):'unknown'}>`;
      break;
    default:result=s.properties?schema({...s,type:'object'}):'unknown';
  }
  return s.nullable?`(${result}) | null`:result;
}
const contentSchema=content=>content?.['application/json']?.schema||Object.values(content||{})[0]?.schema;
let text=`// Generated by sdk/scripts/generate.mjs; do not edit.\n// OpenAPI SHA-256: ${createHash('sha256').update(bytes).digest('hex')}\n\nexport interface Schemas {\n`;
for(const key of Object.keys(spec.components.schemas).sort())text+=`  ${quote(key)}: ${schema(spec.components.schemas[key])};\n`;
text+='}\n\nexport interface Operations {\n';
for(const path of Object.keys(spec.paths).sort()) for(const method of Object.keys(spec.paths[path]).sort()) {
  if(!['get','post','put','patch','delete','head','options'].includes(method))continue;
  const op=spec.paths[path][method],fields=[];
  const params=[...(spec.paths[path].parameters||[]),...(op.parameters||[])];
  for(const location of ['path','query','header']) {
    const entries=params.filter(p=>p.in===location && (location!=='path'||path.includes(`{${p.name}}`)));
    if(entries.length) fields.push(`${location}${entries.some(p=>p.required||location==='path')?'':'?'}: { ${entries.map(p=>`${quote(p.name)}${p.required||location==='path'?'':'?'}: ${schema(p.schema)};`).join(' ')} };`);
  }
  if(op.requestBody)fields.push(`body${op.requestBody.required?'':'?'}: ${schema(contentSchema(op.requestBody.content))};`);
  const success=Object.entries(op.responses||{}).filter(([status])=>/^2\d\d$/.test(status)).map(([,r])=>r.content?schema(contentSchema(r.content)):'void');
  fields.push(`response: ${[...new Set(success)].join(' | ')||'unknown'};`);
  text+=`  ${quote(`${method.toUpperCase()} ${path}`)}: { ${fields.join(' ')} };\n`;
}
text+='}\n';
if(process.argv.includes('--check')) {
  if(await readFile(output,'utf8').catch(()=>null)!==text)throw Error('Generated SDK drift: run npm run generate in sdk after make api-spec');
}else{await mkdir(new URL('../src/',import.meta.url),{recursive:true});await writeFile(output,text);}
