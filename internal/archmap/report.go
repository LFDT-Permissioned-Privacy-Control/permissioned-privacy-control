package archmap

import (
	"fmt"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// FileSize is the measured size of one classified source file.
type FileSize struct {
	Path     string
	Module   string
	Language string
	Lines    int
}

// Measure classifies and counts every in-scope source file under root. It
// fails on a file that no module or several modules claim, and on a file of a
// generated module that does not carry a generated-code header (the flag
// takes code out of the counted totals, so it has to be true).
func Measure(m *Manifest, root string) ([]FileSize, error) {
	files, err := m.Sources(root)
	if err != nil {
		return nil, err
	}
	var out []FileSize
	var problems []string
	for _, f := range files {
		mods, err := m.Classify(f)
		if err != nil {
			return nil, err
		}
		switch len(mods) {
		case 1:
		case 0:
			problems = append(problems, f+": no module claims this file")
			continue
		default:
			names := make([]string, len(mods))
			for i, mod := range mods {
				names[i] = mod.Name
			}
			problems = append(problems, fmt.Sprintf("%s: claimed by several modules: %s", f, strings.Join(names, ", ")))
			continue
		}
		path := filepath.Join(root, filepath.FromSlash(f))
		if mods[0].Generated {
			ok, err := hasGeneratedHeader(path, mods[0].Generator)
			if err != nil {
				return nil, err
			}
			if !ok {
				problems = append(problems, fmt.Sprintf("%s: module %q is marked generated but the file has no generated-code header naming %s", f, mods[0].Name, mods[0].Generator))
				continue
			}
		}
		n, err := CountFile(path)
		if err != nil {
			return nil, err
		}
		out = append(out, FileSize{Path: f, Module: mods[0].Name, Language: Language(f), Lines: n})
	}
	if len(problems) > 0 {
		return out, &ClassificationError{Problems: problems}
	}
	return out, nil
}

// generatedHeader matches the conventional generated-code markers, e.g.
// "// Code generated by protoc-gen-go. DO NOT EDIT." and
// "// Generated by scripts/generate.mjs; do not edit.".
var generatedHeader = regexp.MustCompile(`(?i)^//\s*(code )?generated .*do not edit`)

func hasGeneratedHeader(path, generator string) (bool, error) {
	src, err := readFile(path)
	if err != nil {
		return false, err
	}
	// Only the leading comment block counts, as in Go's convention: a marker
	// after the first line of code does not make a file generated.
	for _, line := range strings.Split(string(src), "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		if !strings.HasPrefix(line, "//") {
			return false, nil
		}
		if generatedHeader.MatchString(line) && strings.Contains(line, generator) {
			return true, nil
		}
	}
	return false, nil
}

// ClassificationError lists files the module map does not classify exactly once.
type ClassificationError struct{ Problems []string }

func (e *ClassificationError) Error() string {
	return fmt.Sprintf("%d source file(s) not classified exactly once:\n  %s", len(e.Problems), strings.Join(e.Problems, "\n  "))
}

// languages in report column order.
var languages = []string{"Go", "Rust", "Java", "Solidity", "SQL", "TypeScript"}

// ReportOptions selects what the report shows.
type ReportOptions struct {
	// OutsideSizes adds sizes for modules outside the perimeter. The
	// committed report leaves them out so that changes to the UI, clients or
	// demos do not require regenerating it.
	OutsideSizes bool
}

// Report renders the per-module size report as Markdown.
func Report(m *Manifest, sizes []FileSize, opts ReportOptions) string {
	type row struct {
		mod   *Module
		files int
		lang  map[string]int
		total int
	}
	rows := map[string]*row{}
	for _, mod := range m.Modules {
		rows[mod.Name] = &row{mod: mod, lang: map[string]int{}}
	}
	for _, s := range sizes {
		r := rows[s.Module]
		r.files++
		r.lang[s.Language] += s.Lines
		r.total += s.Lines
	}
	tierTotal := map[Tier]int{}
	tierLang := map[Tier]map[string]int{TierCore: {}, TierLegacy: {}, TierOutside: {}}
	for _, r := range rows {
		if r.mod.Generated {
			continue
		}
		tierTotal[r.mod.Tier] += r.total
		for l, n := range r.lang {
			tierLang[r.mod.Tier][l] += n
		}
	}
	tiers := []Tier{TierCore, TierLegacy}
	if opts.OutsideSizes {
		tiers = append(tiers, TierOutside)
	}

	var b strings.Builder
	b.WriteString("# Module size report\n\n")
	b.WriteString("Generated by `make perimeter-report` from [modules.toml](modules.toml). Do not edit by hand.\n\n")
	b.WriteString("Sizes are nSLOC: source lines that contain code, without blank and comment-only lines. ")
	b.WriteString("Tests, generated code and tooling outside the classified scope are not counted ")
	b.WriteString("(see [security-perimeter.md](security-perimeter.md#how-sizes-are-counted)).\n\n")

	fmt.Fprintf(&b, "## Totals\n\n| Tier | %s | Total |\n|---|%s---:|\n", strings.Join(languages, " | "), strings.Repeat("---:|", len(languages)))
	for _, t := range tiers {
		fmt.Fprintf(&b, "| %s |", tierLabel(t))
		for _, l := range languages {
			fmt.Fprintf(&b, " %s |", num(tierLang[t][l]))
		}
		fmt.Fprintf(&b, " **%s** |\n", num(tierTotal[t]))
	}

	scopeTotal := map[string]int{}
	scopeMods := map[string][]string{}
	scopeGenerated := map[string][]string{}
	for _, mod := range m.Modules {
		if mod.Tier != TierCore {
			continue
		}
		if mod.Generated {
			scopeGenerated[mod.AuditScope] = append(scopeGenerated[mod.AuditScope], mod.Name)
			continue
		}
		scopeTotal[mod.AuditScope] += rows[mod.Name].total
		scopeMods[mod.AuditScope] = append(scopeMods[mod.AuditScope], mod.Name)
	}
	scopes := make([]string, 0, len(scopeMods))
	for s := range scopeMods {
		scopes = append(scopes, s)
	}
	sort.Strings(scopes)
	b.WriteString("\n## Perimeter by audit scope\n\nEach core module belongs to one audit scope. A scope's figure counts only its own modules; an audit of one scope also covers the code that scope runs on and is called from, so the figure is a lower bound for that audit.\n\n| Scope | Modules | nSLOC |\n|---|---|---:|\n")
	for _, sc := range scopes {
		names := scopeMods[sc]
		sort.Strings(names)
		list := strings.Join(names, ", ")
		if gen := scopeGenerated[sc]; len(gen) > 0 {
			sort.Strings(gen)
			list += "; generated, not counted: " + strings.Join(gen, ", ")
		}
		fmt.Fprintf(&b, "| %s | %s | %s |\n", sc, list, num(scopeTotal[sc]))
	}

	for _, t := range tiers {
		var list []*row
		for _, r := range rows {
			if r.mod.Tier == t && !r.mod.Generated {
				list = append(list, r)
			}
		}
		sort.Slice(list, func(i, j int) bool {
			if list[i].total != list[j].total {
				return list[i].total > list[j].total
			}
			return list[i].mod.Name < list[j].mod.Name
		})
		fmt.Fprintf(&b, "\n## %s\n\n| Module | Files | %s | Total |\n|---|---:|%s---:|\n", tierLabel(t), strings.Join(languages, " | "), strings.Repeat("---:|", len(languages)))
		for _, r := range list {
			fmt.Fprintf(&b, "| `%s` | %d |", r.mod.Name, r.files)
			for _, l := range languages {
				fmt.Fprintf(&b, " %s |", num(r.lang[l]))
			}
			fmt.Fprintf(&b, " %s |\n", num(r.total))
		}
	}
	if !opts.OutsideSizes {
		var names []string
		for _, mod := range m.Modules {
			if mod.Tier == TierOutside && !mod.Generated {
				names = append(names, mod.Name)
			}
		}
		sort.Strings(names)
		b.WriteString("\n## Outside the perimeter\n\nNot linked into a shipped binary; sizes are left out here (`go run ./cmd/perimeter-report -outside` prints them).\n\n| Module | What it is |\n|---|---|\n")
		for _, n := range names {
			fmt.Fprintf(&b, "| `%s` | %s |\n", n, m.Module(n).Summary)
		}
	}

	var generated []*row
	for _, r := range rows {
		if r.mod.Generated && (r.mod.Tier != TierOutside || opts.OutsideSizes) {
			generated = append(generated, r)
		}
	}
	if len(generated) > 0 {
		sort.Slice(generated, func(i, j int) bool { return generated[i].mod.Name < generated[j].mod.Name })
		b.WriteString("\n## Generated code (not counted)\n\n| Module | Tier | Files | Lines |\n|---|---|---:|---:|\n")
		for _, r := range generated {
			fmt.Fprintf(&b, "| `%s` | %s | %d | %s |\n", r.mod.Name, r.mod.Tier, r.files, num(r.total))
		}
	}
	return b.String()
}

func tierLabel(t Tier) string {
	switch t {
	case TierCore:
		return "Perimeter (core)"
	case TierLegacy:
		return "Legacy modes"
	default:
		return "Outside the perimeter"
	}
}

func num(n int) string {
	if n == 0 {
		return "–"
	}
	s := fmt.Sprintf("%d", n)
	if len(s) <= 3 {
		return s
	}
	var parts []string
	for len(s) > 3 {
		parts = append([]string{s[len(s)-3:]}, parts...)
		s = s[:len(s)-3]
	}
	return s + "," + strings.Join(parts, ",")
}

// Touched summarizes which modules a set of changed files (slash paths
// relative to the root, including deleted ones) belongs to: the input for
// scoping a delta audit. inputs are changed audit inputs (dependency locks,
// build files, the rules engine). mapChanged is set when the module map
// itself changed, which can move code across the perimeter without touching
// it.
func Touched(m *Manifest, files, inputs []string, mapChanged bool) string {
	count := map[string]int{}
	var unmapped []string
	for _, f := range files {
		mods, err := m.Classify(f)
		if err != nil || len(mods) != 1 {
			unmapped = append(unmapped, f)
			continue
		}
		count[mods[0].Name]++
	}
	names := make([]string, 0, len(count))
	for n := range count {
		names = append(names, n)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("| Module | Tier | Audit scope | Changed files |\n|---|---|---|---:|\n")
	var core []string
	scopes := map[string]bool{}
	for _, n := range names {
		mod := m.Module(n)
		scope := mod.AuditScope
		if scope == "" {
			scope = "–"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %d |\n", n, mod.Tier, scope, count[n])
		if mod.Tier == TierCore {
			core = append(core, n)
			scopes[mod.AuditScope] = true
		}
	}
	if len(core) == 0 {
		b.WriteString("\nNo core module changed.\n")
	} else {
		list := make([]string, 0, len(scopes))
		for s := range scopes {
			list = append(list, s)
		}
		sort.Strings(list)
		fmt.Fprintf(&b, "\nCore modules changed: %s. Audit scopes: %s.\n", strings.Join(core, ", "), strings.Join(list, ", "))
	}
	if len(unmapped) > 0 {
		fmt.Fprintf(&b, "Not in the module map: %s\n", strings.Join(unmapped, ", "))
	}
	if len(inputs) > 0 {
		fmt.Fprintf(&b, "Build, dependency and rule inputs changed: %s\n", strings.Join(inputs, ", "))
	}
	if mapChanged {
		b.WriteString("The module map changed: review its tier, export, dispatch and mount changes as part of the audit; " +
			"files classified with the current map may have been inside the perimeter before.\n")
	}
	return b.String()
}
