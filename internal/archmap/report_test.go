func TestParseRejectsMoreInvalidManifests(t *testing.T) {
	cases := map[string]struct{ old, new, wantErr string }{
		"unknown key": {`owner = "maintainers"
paths = ["src/gate/**"]`, `owner = "maintainers"
colour = "red"
paths = ["src/gate/**"]`, "unknown keys"},
		"missing owner": {`owner = "maintainers"
paths = ["src/gate/**"]`, `paths = ["src/gate/**"]`, `module "gate" needs an owner`},
		"scope on outside": {`summary = "renders"`, `summary = "renders"
audit_scope = "access"`, `module "ui": audit_scope applies to core modules only`},
		"duplicate dispatch": {`reason = "selects the legacy path only in legacy mode"`, `reason = "selects the legacy path only in legacy mode"

[[dispatch]]
file = "src/gate/check.go"
function = "Router.Serve"
objects = ["Old"]
reason = "again"`, "dispatch src/gate/check.go Router.Serve is declared twice"},
		"bad glob": {`paths = ["src/ui/**"]`, `paths = ["src/ui/[a]"]`, "character classes are not supported"},
	}
	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			require.Equal(t, 1, strings.Count(validManifest, tc.old), "fixture text must occur once")
			_, err := Parse([]byte(strings.Replace(validManifest, tc.old, tc.new, 1)))
			require.ErrorContains(t, err, tc.wantErr)
		})
	}
}

