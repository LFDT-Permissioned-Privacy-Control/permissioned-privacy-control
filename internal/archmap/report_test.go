func TestIsAuditInput(t *testing.T) {
	m, err := Parse([]byte(validManifest + `
[audit_inputs]
paths = ["go.sum", "internal/archmap/**"]
`))
	require.NoError(t, err)
	for path, want := range map[string]bool{"go.sum": true, "internal/archmap/check.go": true, "README.md": false} {
		got, err := m.IsAuditInput(path)
		require.NoError(t, err)
		require.Equal(t, want, got, path)
	}
}

func TestChangesSortsPathsAndReportsTheRulesEngine(t *testing.T) {
	m, err := Parse([]byte(validManifest + `
[audit_inputs]
paths = ["go.sum", "src/gate/rules/**"]
`))
	require.NoError(t, err)
	files, inputs, mapChanged, err := m.Changes([]string{
		"src/gate/rules/engine.go", // a source file and an audit input: listed as both
		"go.sum",
		"docs/modules.toml",
		"src/ui/page.go",
		"README.md",
	}, "docs/modules.toml")
	require.NoError(t, err)
	require.Equal(t, []string{"src/gate/rules/engine.go", "src/ui/page.go"}, files)
	require.Equal(t, []string{"src/gate/rules/engine.go", "go.sum"}, inputs)
	require.True(t, mapChanged)
}
