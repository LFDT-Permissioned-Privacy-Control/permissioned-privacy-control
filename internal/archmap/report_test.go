func TestGeneratedHeaderMustLeadTheFile(t *testing.T) {
	dir := t.TempDir()
	write := func(name, body string) string {
		p := filepath.Join(dir, name)
		require.NoError(t, os.WriteFile(p, []byte(body), 0o644))
		return p
	}
	ok, err := hasGeneratedHeader(write("a.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage a\n"), "protoc-gen-go")
	require.NoError(t, err)
	require.True(t, ok)
	ok, err = hasGeneratedHeader(write("b.go", "package b\n\n// Code generated by hand. DO NOT EDIT.\nvar x = 1\n"), "hand")
	require.NoError(t, err)
	require.False(t, ok, "a marker after the package clause does not make the file generated")
}

func TestSourcesSkipsOnlyBuildOutputDirectories(t *testing.T) {
	root := t.TempDir()
	write := func(rel string) {
		p := filepath.Join(root, rel)
		require.NoError(t, os.MkdirAll(filepath.Dir(p), 0o755))
		require.NoError(t, os.WriteFile(p, []byte("package x\n"), 0o644))
	}
	write("src/target/kept.go")            // a source directory named target
	write("src/crate/Cargo.toml")          // a Rust crate ...
	write("src/crate/target/skipped.go")   // ... whose build output is skipped
	write("src/node_modules/x/skipped.go") // dependencies
	write(".tmp/skipped.go")               // scratch space at the root
	write("src/.tmp/kept.go")              // not at the root
	m, err := Parse([]byte(validManifest))
	require.NoError(t, err)
	files, err := m.Sources(root)
	require.NoError(t, err)
	require.Equal(t, []string{"src/.tmp/kept.go", "src/target/kept.go"}, files)
}

