func TestMeasureAndReport(t *testing.T) {
	root := t.TempDir()
	write := func(rel, body string) {
		p := filepath.Join(root, rel)
		require.NoError(t, os.MkdirAll(filepath.Dir(p), 0o755))
		require.NoError(t, os.WriteFile(p, []byte(body), 0o644))
	}
	write("src/gate/check.go", "package gate\n\n// doc\nfunc Check() bool {\n\treturn true\n}\n")
	write("src/store/rows.go", "package store\n")
	write("src/ui/page.go", "package ui\n\nvar x = 1\n")
	write("src/gen/x.pb.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage gen\n\nvar y = 2\n")
	write("src/sdk/gen.go", "// Code generated by sdkgen. DO NOT EDIT.\n\npackage sdk\n")

	m, err := Parse([]byte(validManifest + `
[[module]]
name = "proto"
tier = "core"
audit_scope = "access"
generated = true
generator = "protoc-gen-go"
summary = "generated protocol code"
owner = "maintainers"
paths = ["src/gen/**"]

[[module]]
name = "sdkgen"
tier = "outside"
generated = true
generator = "sdkgen"
summary = "generated client types"
owner = "maintainers"
paths = ["src/sdk/**"]
`))
	require.NoError(t, err)
	sizes, err := Measure(m, root)
	require.NoError(t, err)
	require.Equal(t, []FileSize{
		{Path: "src/gate/check.go", Module: "gate", Language: "Go", Lines: 4},
		{Path: "src/gen/x.pb.go", Module: "proto", Language: "Go", Lines: 2},
		{Path: "src/sdk/gen.go", Module: "sdkgen", Language: "Go", Lines: 1},
		{Path: "src/store/rows.go", Module: "store", Language: "Go", Lines: 1},
		{Path: "src/ui/page.go", Module: "ui", Language: "Go", Lines: 2},
	}, sizes)

	report := Report(m, sizes, ReportOptions{})
	require.Contains(t, report, "| Perimeter (core) | 5 | – | – | – | – | – | **5** |")
	require.NotContains(t, report, "target")
	require.Contains(t, report, "| `gate` | 1 | 4 |")
	require.Contains(t, report, "| access | gate, store; generated, not counted: proto | 5 |")
	require.Contains(t, report, "## Generated code (not counted)")
	require.Contains(t, report, "| `proto` | core | 1 | 2 |")
	// Outside modules are listed without sizes, so their churn (UI, demos)
	// does not change the committed report.
	require.Contains(t, report, "| `metrics` | counters |")
	require.NotContains(t, report, "| Outside the perimeter |")

	require.NotContains(t, report, "| `sdkgen` |", "outside generated code is not sized in the committed report")

	full := Report(m, sizes, ReportOptions{OutsideSizes: true})
	require.Contains(t, full, "| `sdkgen` | outside | 1 | 1 |")
	require.Contains(t, full, "| Outside the perimeter | 2 |")
	require.Contains(t, full, "| `ui` | 1 | 2 |")

	write("src/orphan/x.go", "package orphan\n")
	write("src/gen/y.go", "package gen\n")
	write("src/gen/z.go", "// Code generated by hand. DO NOT EDIT.\n\npackage gen\n")
	_, err = Measure(m, root)
	var ce *ClassificationError
	require.True(t, errors.As(err, &ce), "%v", err)
	require.Equal(t, []string{
		"src/gen/y.go: module \"proto\" is marked generated but the file has no generated-code header naming protoc-gen-go",
		"src/gen/z.go: module \"proto\" is marked generated but the file has no generated-code header naming protoc-gen-go",
		"src/orphan/x.go: no module claims this file",
	}, ce.Problems)
}

